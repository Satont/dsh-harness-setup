#!/usr/bin/env node
/**
 * sync-standard-preset — generate the profile-patch override of the shipped
 * `standard` Agent preset with tuned compaction settings (and optional
 * summarization target), keeping everything else from the bundle preset.
 *
 * DSH mounts compaction per Agent preset (`compaction-basic` row inside
 * `dsh-web-app/presets/standard.patch.yml`), so tuning it means overriding the
 * `preset-standard` row's complete `config.plugins` list from the profile patch
 * — exactly what "override a shipped preset by row id" means in DSH. This
 * script regenerates that block from the installed bundle, so a DSH update is
 * followed by re-running it instead of hand-editing 130 lines.
 *
 * Usage:
 *   node sync-standard-preset.mjs [--threshold-ratio 0.85] [--headroom 24576]
 *        [--retain-ratio 0.15] [--summary-max-tokens 24576] [--auto true|false]
 *        [--summarization-provider deepseek] [--summarization-model deepseek-chat]
 *        [--preset <path to standard.patch.yml>] [--profile-patch <path>] [--dry-run]
 *
 * Defaults: 0.85 / 24576 / 0.15 / 24576 / true, no fixed summarization target
 * (the routed model writes the summary, which reuses the warm request prefix).
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const argv = process.argv.slice(2);
function opt(name, fallback) {
  const i = argv.indexOf(name);
  return i >= 0 && argv[i + 1] !== undefined ? argv[i + 1] : fallback;
}
const dry = argv.includes("--dry-run");
const thresholdRatio = Number(opt("--threshold-ratio", "0.85"));
const headroom = Number(opt("--headroom", "24576"));
const retainRatio = Number(opt("--retain-ratio", "0.15"));
const summaryMax = Number(opt("--summary-max-tokens", "24576"));
const auto = String(opt("--auto", "true")) === "true";
const summarizationProvider = opt("--summarization-provider", "");
const summarizationModel = opt("--summarization-model", "");

const MARK_START = "# >>> model-tuning:standard-preset (generated by model-tuning/sync-standard-preset.mjs; edit via the script)";
const MARK_END = "# <<< model-tuning:standard-preset";

function findStandardPreset() {
  if (opt("--preset")) return path.resolve(opt("--preset"));
  const roots = [
    path.join(os.homedir(), ".local/share/mise/installs/node"),
    path.join(os.homedir(), ".local/share/mise/installs"),
    "/usr/local/lib/node_modules",
    "/usr/lib/node_modules",
  ];
  const candidates = [];
  for (const root of roots) {
    let versions = [];
    try { versions = fs.readdirSync(root); } catch { continue; }
    for (const version of versions) {
      const bases = [
        path.join(root, version, "lib/node_modules/@deepseek-ai/dsh"),
        path.join(root, version, "node_modules/@deepseek-ai/dsh"),
      ];
      for (const base of bases) {
        const file = path.join(base, "node_modules/@deepseek-ai/dsh-web-app/presets/standard.patch.yml");
        if (fs.existsSync(file)) candidates.push(file);
      }
    }
  }
  if (candidates.length === 0) throw new Error("standard.patch.yml not found; pass --preset <path>");
  // Prefer the newest mise version: the last candidate in lexicographic order.
  candidates.sort();
  return candidates.at(-1);
}

function profilePatchPath() {
  if (opt("--profile-patch")) return path.resolve(opt("--profile-patch"));
  const home = process.env.DSH_HOME ? path.resolve(process.env.DSH_HOME) : path.join(os.homedir(), ".dsh");
  return path.join(home, "profiles/web/cordis.patch.yml");
}

function generateBlock(source) {
  const lines = source.split("\n");
  const start = lines.findIndex((line) => /^\s*plugins:\s*$/.test(line));
  if (start < 0) throw new Error("no `plugins:` list in the standard preset");
  const body = lines.slice(start + 1).filter((line, index, all) => !(line.trim() === "" && all.slice(index).every((rest) => rest.trim() === "")));
  const indent = body.filter((line) => line.trim() !== "").map((line) => line.match(/^\s*/)[0].length).sort((a, b) => a - b)[0];
  const dedented = body.map((line) => (line.trim() === "" ? "" : line.slice(indent)));

  // compaction-basic sits inside the `compaction` group, so match it at any depth.
  const rowIndex = dedented.findIndex((line) => /^(\s*)- id: compaction-basic\s*$/.test(line));
  if (rowIndex < 0) throw new Error("no `compaction-basic` row in the standard preset");
  const rowIndent = /^(\s*)/.exec(dedented[rowIndex])[1];
  const childIndent = rowIndent + "  ";
  const keyIndent = childIndent + "  ";
  let insertAt = rowIndex + 1;
  while (insertAt < dedented.length && !new RegExp(`^${childIndent}name:`).test(dedented[insertAt])) insertAt += 1;
  insertAt += 1;
  const config = [
    `${childIndent}config:`,
    `${keyIndent}thresholdRatio: ${thresholdRatio}`,
    `${keyIndent}headroomTokens: ${headroom}`,
    `${keyIndent}retainRatio: ${retainRatio}`,
    `${keyIndent}maxTokens: ${summaryMax}`,
    `${keyIndent}auto: ${auto}`,
  ];
  if (summarizationProvider || summarizationModel) {
    if (!summarizationProvider || !summarizationModel) throw new Error("set --summarization-provider and --summarization-model together");
    config.push(`${keyIndent}summarizationProvider: ${summarizationProvider}`);
    config.push(`${keyIndent}summarizationModel: ${summarizationModel}`);
  }
  const plugins = [...dedented.slice(0, insertAt), ...config, ...dedented.slice(insertAt)];
  return { plugins };
}

function renderPatch(source) {
  const { plugins } = generateBlock(source);
  return [
    MARK_START,
    "- id: preset-standard",
    "  config:",
    "    id: standard",
    "    order: 1",
    "    plugins:",
    ...plugins.map((line) => (line === "" ? "" : `      ${line}`)),
    MARK_END,
    "",
  ].join("\n");
}

const standard = findStandardPreset();
const profilePatch = profilePatchPath();
const source = fs.readFileSync(standard, "utf8");
const rendered = renderPatch(source);
let current = "";
try { current = fs.readFileSync(profilePatch, "utf8"); } catch { current = ""; }
const startAt = current.indexOf(MARK_START);
const endAt = current.indexOf(MARK_END);
let next;
if (startAt >= 0 && endAt > startAt) {
  next = current.slice(0, startAt).replace(/\s+$/, "\n") + rendered + current.slice(endAt + MARK_END.length).replace(/^\s*\n?/, "");
} else {
  next = current.replace(/\s*$/, "\n") + "\n" + rendered;
}
if (!dry) {
  const backup = `${profilePatch}.bak-model-tuning-${new Date().toISOString().replace(/[:.]/g, "-")}`;
  if (fs.existsSync(profilePatch)) fs.copyFileSync(profilePatch, backup);
  fs.writeFileSync(profilePatch, next);
  console.log(`tuned preset written: ${profilePatch}`);
  console.log(`source preset: ${standard}`);
  console.log(`backup: ${backup}`);
  console.log(`compaction: thresholdRatio=${thresholdRatio} headroomTokens=${headroom} retainRatio=${retainRatio} maxTokens=${summaryMax} auto=${auto}${summarizationProvider ? ` summarizer=${summarizationProvider}/${summarizationModel}` : ""}`);
} else {
  console.log(rendered);
}
